// Writes dist/sw.js after a build, listing that build's files so the app keeps
// working with no signal once it has been opened - the point of a page you add
// to the home screen rather than one you have to load every time.
//
// The list has to be generated because Vite hashes the asset names, and the
// cache is named after this build so an older one is cleared out rather than
// left behind.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

const dist = process.argv[2] || 'dist';
if (!fs.existsSync(dist)) {
  console.error(`make-sw: no ${dist}/ to work from - run the build first`);
  process.exit(1);
}

const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else files.push(path.relative(dist, full).split(path.sep).join('/'));
  }
})(dist);

const assets = files.filter((f) => f !== 'sw.js');
const hash = crypto.createHash('sha1');
for (const f of assets.slice().sort()) hash.update(f).update(fs.readFileSync(path.join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/make-sw.mjs - do not edit by hand.
const CACHE = 'skp-viewer-${version}';
const ASSETS = ${JSON.stringify(['./', ...assets], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE)
      // One bad entry shouldn't sink the whole install, so add them singly.
      .then((c) => Promise.all(ASSETS.map((a) => c.add(a).catch(() => {}))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // The page itself: take a fresh copy when there is signal, so a new build is
  // picked up, but fall back to the stored one when there isn't.
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
          return res;
        })
        .catch(() => caches.match(req).then((hit) => hit || caches.match('./')))
    );
    return;
  }
  // Everything else is content-hashed by the build, so a stored copy is always
  // the right one.
  e.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res && res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
      }
      return res;
    }))
  );
});
`;

fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`make-sw: ${dist}/sw.js lists ${assets.length} files (build ${version})`);
